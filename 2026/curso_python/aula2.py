# print(12, 34) -> permite exibir uma lista de números no console e coloca espaço entre eles. São chamados de argumentos não nomeados. Também, é possível passar 
# outros argumentos não nomeados de outros tipos
# O argumento nomeado chamado sep do método print, define os separadores entre os argumentos não nomeados
# O argumento nomeado chamado end do método print, define o caractere no final após os argumentos não nomeados. Por padrão, ele coloca uma quebra de linha (\n)
# Pular linha do windows mais antigo: \r\n -> CRLF
# Pular linha do linux: \r\n -> LF
# Python é case-sensitive
print(12, 34, 1011, sep='-', end='\n##')
print(56, 78, sep="-", end='\n')
print(9, 10, sep="-", end='\n')